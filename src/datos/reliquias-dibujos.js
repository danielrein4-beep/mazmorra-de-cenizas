function dibujarReliquia(x, id, cx, cy, s) {
  const R0 = reliquia(id);
  if (!R0) return;
  const M = FORMAS_RELIQUIA[R0.f],
    col = { X: R0.c, W: '#ffffff', K: '#0b0812', Y: '#ffd24a', S: '#5a5070' };
  M.forEach((fila, j) =>
    [...fila].forEach((ch, i) => {
      if (!col[ch]) return;
      x.fillStyle = col[ch];
      x.fillRect(Math.round(cx - 6 * s + i * s), Math.round(cy - 6 * s + j * s), s, s);
    }),
  );
}
