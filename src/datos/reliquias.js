const reliquia = id => RELIQUIAS.find(r => r.id == id);
const tiene = (P, id) => !!(P && P.rel && P.rel[id]);
const sinergia = (P, id) => {
  const s = SINERGIAS.find(x => x.id == id);
  return tiene(P, s.a) && tiene(P, s.b);
};

// Una reliquia al azar que P todavía no tiene: legendarias raras, comunes seguido.
function reliquiaAlAzar(P, sinLegendaria) {
  const pool = RELIQUIAS.filter(r => !tiene(P, r.id) && !(sinLegendaria && r.r == 'l')),
    peso = r => (r.r == 'c' ? 10 : r.r == 'r' ? 5 : 1.4);
  let x = Math.random() * pool.reduce((s, r) => s + peso(r), 0);
  for (const r of pool) if ((x -= peso(r)) <= 0) return r.id;
  return pool.length ? pool[0].id : null;
}
